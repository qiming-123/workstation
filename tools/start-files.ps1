[CmdletBinding()]
param(
    [string] $ConfigPath = (Join-Path $PSScriptRoot '../config.json'),
    [string] $Python = 'python',
    [string] $StateDirectory = (Join-Path $env:LOCALAPPDATA 'workstation/copyparty'),
    [string] $TestVolumeRoot,
    [string] $TestSecondVolumeRoot
)

$ErrorActionPreference = 'Stop'
$settings = Get-Content -LiteralPath $ConfigPath -Raw -Encoding UTF8 | ConvertFrom-Json
$backend = $settings.fileBackend
if ($backend.origin -cnotmatch '^http://127\.0\.0\.1:(\d{1,5})/?$') {
    throw 'fileBackend.origin must be an HTTP origin on 127.0.0.1 with an explicit port.'
}
$port = [int] $Matches[1]
if ($port -le 0 -or $port -gt 65535 -or $port -eq $settings.port) {
    throw 'Set a valid file backend port different from the workstation port.'
}
if ($backend.password -cnotmatch '^[0-9a-f]{64}$') {
    throw 'fileBackend.password must have the format generated by npm run init.'
}

$volumes = [ordered]@{}
if ($TestVolumeRoot) {
    $volumes['C'] = Get-Item -LiteralPath $TestVolumeRoot
    if ($TestSecondVolumeRoot) {
        $volumes['D'] = Get-Item -LiteralPath $TestSecondVolumeRoot
    }
} else {
    if ($TestSecondVolumeRoot) {
        throw 'Use TestSecondVolumeRoot together with TestVolumeRoot.'
    }
    [IO.DriveInfo]::GetDrives() | Where-Object IsReady | ForEach-Object {
        $name = $_.Name.Substring(0, 1).ToUpperInvariant()
        $volumes[$name] = $_.RootDirectory
    }
}
if ($volumes.Count -eq 0) {
    throw 'No ready Windows drives were found.'
}

$lines = @('[accounts]', ('  workstation: ' + $backend.password))
foreach ($mount in $volumes.Keys) {
    $root = $volumes[$mount]
    if ($root -isnot [IO.DirectoryInfo] -or $root.FullName -match '\r|\n|  #') {
        throw 'A volume root must be a local filesystem directory usable by copyparty.'
    }
    $access = 'rwmd.'
    if ($TestSecondVolumeRoot -and $mount -eq 'D') {
        $access = 'r'
    }
    $lines += @('', ('[/' + $mount + ']'), ('  ' + $root.FullName), '  accs:', ('    ' + $access + ': workstation'))
}

$state = [IO.Directory]::CreateDirectory($StateDirectory).FullName
$copypartyConfig = Join-Path $state ([Guid]::NewGuid().ToString('N') + '.conf')
[IO.File]::WriteAllLines($copypartyConfig, $lines, [Text.UTF8Encoding]::new($false))
$savedXdg = $env:XDG_CONFIG_HOME
try {
    $env:XDG_CONFIG_HOME = $state
    $copypartyArgs = @(
        '-m', 'copyparty', '-c', $copypartyConfig, '-i', '127.0.0.1', '-p', $port, '--http-only',
        '--rp-loc', '/storage', '--rproxy', '1', '--xff-src', '127.0.0.1/32',
        '--no-html', '--no-mime', '--no-readme', '--no-logues', '--no-reload', '--no-robots',
        '--no-thumb', '--no-mtag-ff', '--dotpart', '--dav-auth', '-ed',
        '--ui-noacci', '--ui-nosrvi', '--ui-nocpla', '--ui-norepl',
        '--name', 'workstation', '--name-url', '/storage/', '--hist', (Join-Path $state 'volumes')
    )
    & $Python @copypartyArgs
    if ($LASTEXITCODE -ne 0) {
        throw "copyparty exited with status $LASTEXITCODE."
    }
} finally {
    $env:XDG_CONFIG_HOME = $savedXdg
    Remove-Item -LiteralPath $copypartyConfig -ErrorAction SilentlyContinue
}
